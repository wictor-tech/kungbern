const dicts: Record<Lang, Record<Key, string>> = { sv, en };

export function makeT(lang: Lang) {
  const d = dicts[lang];
  return (k: Key): string => d[k] ?? k;
}

export type T = ReturnType<typeof makeT>;

export function fmtNum(lang: Lang, v: number, digits = 0): string {
  if (!Number.isFinite(v)) return "–";
  return new Intl.NumberFormat(lang === "sv" ? "sv-SE" : "en-GB", { maximumFractionDigits: digits, minimumFractionDigits: digits }).format(v);
}

export function fmtMoney(lang: Lang, v: number, currency: string): string {
  if (!Number.isFinite(v)) return "–";
  return new Intl.NumberFormat(lang === "sv" ? "sv-SE" : "en-GB", { style: "currency", currency, maximumFractionDigits: 0 }).format(v);
}
