/* Cache-busting for versioned assets (v20).

   Files under /assets/ requested with ?v= are served with "immutable" and a one-year cache
   (server.mjs). The ?v value must therefore change whenever the file changes. Hand-maintained
   values went stale (e.g. app.js changed in v19 but was still referenced as ?v=17.0), so returning
   visitors kept old code. This script sets ?v to a short content hash of the referenced file.

   node scripts/asset-versions.mjs           rewrite the HTML files
   node scripts/asset-versions.mjs --check   exit 1 if any reference is out of date (CI) */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const REF = /((?:src|href)=")(\/?assets\/[\w./-]+\.(?:js|css))\?v=([\w.-]+)(")/g;
// Generated by the server per request (visibility-dependent); it sets its own no-cache header.
const DYNAMIC = new Set(['assets/product-image-map.js']);

export function hashFor(relative) {
  return crypto.createHash('sha256').update(fs.readFileSync(path.join(root, relative))).digest('hex').slice(0, 10);
}

export function plan() {
  const changes = [];
  const files = fs.readdirSync(root).filter(name => name.endsWith('.html'));
  const output = {};
  for (const file of files) {
    const before = fs.readFileSync(path.join(root, file), 'utf8');
    const after = before.replace(REF, (match, start, ref, version, end) => {
      const relative = ref.replace(/^\//, '');
      if (DYNAMIC.has(relative) || !fs.existsSync(path.join(root, relative))) return match;
      const next = hashFor(relative);
      if (next !== version) changes.push({ file, asset: relative, from: version, to: next });
      return `${start}${ref}?v=${next}${end}`;
    });
    output[file] = after;
  }
  return { changes, output };
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const { changes, output } = plan();
  if (process.argv.includes('--check')) {
    if (changes.length) {
      console.error(`${changes.length} asset reference(s) have a stale ?v= value:`);
      for (const change of changes.slice(0, 20)) console.error(`  ${change.file}: ${change.asset} ?v=${change.from} (should be ${change.to})`);
      console.error('Run: node scripts/asset-versions.mjs');
      process.exit(1);
    }
    console.log('Asset versions are current.');
  } else {
    for (const [file, text] of Object.entries(output)) fs.writeFileSync(path.join(root, file), text);
    console.log(`Asset versions: ${changes.length} reference(s) updated.`);
  }
}
