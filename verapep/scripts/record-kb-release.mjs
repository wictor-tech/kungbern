/* Maintainer tool: records the hashes of the shipped Ask Vera answers in
   data/support-kb-history.json, so a later release can recognise them as
   "previously shipped" (and therefore safe to update) in existing databases.
   Run once per release after editing data/support-kb.json:
     node scripts/record-kb-release.mjs 17.0
   Optional: --from <file.json> to record an older shipped file. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { hashEntry, hashText } from '../lib/support-kb-migration.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const release = process.argv[2];
if (!release) { console.error('Usage: node scripts/record-kb-release.mjs <release> [--from file.json]'); process.exit(1); }
const fromIndex = process.argv.indexOf('--from');
const source = fromIndex > -1 ? path.resolve(process.argv[fromIndex + 1]) : path.join(root, 'data', 'support-kb.json');
const historyFile = path.join(root, 'data', 'support-kb-history.json');
const history = fs.existsSync(historyFile) ? JSON.parse(fs.readFileSync(historyFile, 'utf8')) : { version: 1, entries: {}, fallbacks: [] };
const kb = JSON.parse(fs.readFileSync(source, 'utf8'));
let added = 0;
for (const entry of kb.entries) {
  const hash = hashEntry(entry);
  history.entries[entry.id] ||= [];
  // keywordsHash lets the migration recognise a shipped answer whose text an admin edited (old editor renamed ids).
  const keywordsHash = hashText(Array.isArray(entry.keywords) && entry.keywords.length ? entry.keywords.join(' ') : entry.question);
  const known = history.entries[entry.id].find(version => version.hash === hash);
  if (!known) { history.entries[entry.id].push({ release, hash, keywordsHash }); added += 1; }
  else if (!known.keywordsHash) known.keywordsHash = keywordsHash;
}
const fallbackHash = hashText(kb.fallback);
if (!history.fallbacks.some(item => item.hash === fallbackHash)) { history.fallbacks.push({ release, hash: fallbackHash }); added += 1; }
history.note = 'Content hashes of every Ask Vera answer shipped by a release. Used by the knowledge-base migration to tell outdated shipped answers (safe to update) from admin edits (always kept). Generated by scripts/record-kb-release.mjs — do not edit by hand.';
fs.writeFileSync(historyFile, `${JSON.stringify(history, null, 2)}\n`);
console.log(`Recorded ${added} new hash(es) for release ${release} from ${path.relative(root, source)}.`);
