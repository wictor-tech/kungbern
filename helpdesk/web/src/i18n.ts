export const STRINGS: Record<Lang, Strings> = { sv, en, da, no, fi, de, fr, nl, pl };

export function detectLang(): Lang {
  const stored = (() => { try { return localStorage.getItem("lup-help-lang"); } catch { return null; } })();
  const all = Object.keys(STRINGS);
  if (stored && all.includes(stored)) return stored as Lang;
  for (const l of navigator.languages ?? [navigator.language]) {
    const code = l.toLowerCase().slice(0, 2);
    const mapped = code === "nb" || code === "nn" ? "no" : code;
    if (all.includes(mapped)) return mapped as Lang;
  }
  return "sv";
}

